"""
Data loader for the Southern Munich district heating case study.

Data sources:
  Munich_tech_data.xlsx  — technology / storage / prices / extra / HP COP
                           Parameters from Kaufmann et al. (ECM 2026): Table 3.1 (CAPEX),
                           §2.2 (fuel prices, emission factors), §2.2.3 (maintenance).
  Munich_DH_data.xlsx    — hourly profiles (generated by create_munich_data.py from DhnData.csv)
                           Columns: heat demand, electricity prices,
                           supply/return temperatures (measured & fixed design values).

Technologies modelled (all from Kaufmann et al., ECM 2026):
  - Geothermal Heat   — existing, 14.0 MW direct (brine 106→65°C, coupled with HTHP)
  - HTHP              — existing, 8.82 MW condenser output (brine 65→45°C evap side);
                        SAPHEA Capacity Increase model; COP patched per (d,h) in run_rd.py
  - Gas Boiler        — investable, η=103% condensing
  - Electric Boiler   — investable, η=99%
"""

import re
from pathlib import Path
from typing import Any, Dict, Tuple

import pandas as pd
from loguru import logger


class DataLoadError(Exception):
    """Raised when a required file or column is missing."""


# ── Technology data (Heat Generators sheet) ───────────────────────────────────

def load_munich_technologies(filepath: str | Path) -> Dict[str, Dict[str, Any]]:
    """
    Load heat generator parameters from Munich_tech_data.xlsx → 'Heat Generators'.

    Returns dict keyed by technology name with the same fields as the Kranj
    equivalent, so the same model code can consume both case studies unchanged.
    """
    filepath = Path(filepath)
    if not filepath.exists():
        raise DataLoadError(f"File not found: {filepath}")

    df = pd.read_excel(filepath, sheet_name="Heat Generators")
    has_install_year = "Installation Year" in df.columns

    technologies: Dict[str, Dict[str, Any]] = {}
    for _, row in df.iterrows():
        name = str(row["name"]).strip()
        technologies[name] = {
            "installed_capacity_MW":   float(row["installed capacity (MW_th)"]),
            "efficiency_th":           float(row["efficiency th"]),
            "efficiency_el":           float(row["efficiency el"]),
            "capex_EUR_per_MW":        float(row["investment costs (EUR/MW_th)"]),
            "opex_fix_EUR_per_MWa":    float(row["OPEX fix (EUR/MWa)"]),
            "opex_var_EUR_per_MWh":    float(row["OPEX var (EUR/MWh)"]),
            "energy_carrier":          str(row["energy carrier"]).strip()
                                       if "energy carrier" in row else None,
            "coldstart_cost_EUR":      float(row["Coldstart costs (EUR/Start)"])
                                       if "Coldstart costs (EUR/Start)" in df.columns else 0.0,
            "cold_start_time_h":       int(float(row["Start up time (h)"]))
                                       if "Start up time (h)" in df.columns else 0,
            "ramp_cost_EUR_per_MW":    float(row["Ramping costs [EUR/MWh]"])
                                       if "Ramping costs [EUR/MWh]" in df.columns else 0.0,
            "min_load_factor":         float(row["Min Load factor"])
                                       if "Min Load factor" in df.columns else 0.0,
            "lifetime_a":              int(row["life time"]),
            "max_potential_MWh":       float(row["Maximal Available Potential [MWh]"]),
            "max_output_MW":           float(row["Maximal Output Power [MW]"]),
        }
        if has_install_year:
            val = row["Installation Year"]
            technologies[name]["installation_year"] = int(val) if pd.notna(val) else None


    logger.info(f"Loaded {len(technologies)} Munich technologies from {filepath.name}")
    return technologies


# ── Storage data (Heat Storage sheet) ─────────────────────────────────────────

def load_munich_storage(filepath: str | Path) -> Dict[str, Dict[str, Any]]:
    """
    Load heat storage parameters from Munich_tech_data.xlsx → 'Heat Storage'.
    Buffer/STTS tank (1000 m³, 40.6 MWh) as described in Kaufmann et al. §2.1.
    """
    filepath = Path(filepath)
    df = pd.read_excel(filepath, sheet_name="Heat Storage")
    has_install_year = "Installation Year" in df.columns

    storages: Dict[str, Dict[str, Any]] = {}
    for _, row in df.iterrows():
        name = str(row["name"]).strip()
        storages[name] = {
            "capacity_MWh":          float(row["Storage Capacity [MWh]"]),
            "hourly_loss_frac":      float(row["Hourly Stoarge Losses [%]"]) / 100,
            "tau_charge_h":          float(row["Minimum Charge Time [h]"]),
            "tau_discharge_h":       float(row["Minimum Discharge Time [h]"]),
            "charge_eff":            float(row["loading efficiency"]),
            "discharge_eff":         float(row["unloading efficiency"]),
            "capex_EUR_per_MWh":     float(
                row["Invesment costs for additional storage capacity  [€/MWh]"]
            ),
            "opex_fix_EUR_per_MWh":  float(row["OPEX fix [€/MWh]"]),
            "opex_var_EUR_per_MWh":  float(row["OPEX var [€/MWh]"])
                                     if "OPEX var [€/MWh]" in df.columns else 0.0,
            "lifetime_a":            int(row["Life Time [a]"]),
            "max_capacity_MWh":      float(row["Maximum Storage Capacity [MWh]"])
                                     if "Maximum Storage Capacity [MWh]" in df.columns else 0.0,
        }
        if has_install_year:
            val = row["Installation Year"]
            storages[name]["installation_year"] = int(val) if pd.notna(val) else None

    logger.info(f"Loaded {len(storages)} Munich storage systems from {filepath.name}")
    return storages


# ── Energy carrier prices & emission factors ──────────────────────────────────

def load_energy_prices(filepath: str | Path) -> Dict[str, Any]:
    """
    Load energy carrier prices and emission factors from
    Munich_tech_data.xlsx → 'prices and emmision factors'.

    Carriers: geothermal (free), electricity (price comes from DH data, EF in sheet),
              natural gas (Kaufmann 2026 industrial price, escalating).
    """
    filepath = Path(filepath)
    df = pd.read_excel(filepath, sheet_name="prices and emmision factors")

    price_cols: Dict[int, str] = {}
    emission_cols: Dict[int, str] = {}
    for col in df.columns:
        col_str = str(col).strip()
        m = re.match(r'prices?[_\s]*(\d{4})', col_str, re.IGNORECASE)
        if m:
            price_cols[int(m.group(1))] = col_str
            continue
        m = re.match(r'emission[_\s]*factor[_\s]*(\d{4})', col_str, re.IGNORECASE)
        if m:
            emission_cols[int(m.group(1))] = col_str

    if not price_cols:
        raise DataLoadError(
            "No period price columns found in 'prices and emmision factors' sheet."
        )
    if not emission_cols:
        raise DataLoadError(
            "No period emission columns found in 'prices and emmision factors' sheet."
        )

    periods = sorted(set(price_cols) | set(emission_cols))
    prices: Dict[str, Any] = {}
    for _, row in df.iterrows():
        carrier = str(row["energy carrier"]).strip()

        price_series: Dict[int, float] = {}
        last = 0.0
        for yr in sorted(price_cols):
            raw = row[price_cols[yr]]
            last = float(raw) if pd.notna(raw) else last
            price_series[yr] = last

        emis_series: Dict[int, float] = {}
        last = 0.0
        for yr in sorted(emission_cols):
            raw = row[emission_cols[yr]]
            last = float(raw) if pd.notna(raw) else last
            emis_series[yr] = last

        prices[carrier] = {
            "price_by_period":    price_series,
            "emission_by_period": emis_series,
        }

    logger.info(
        f"Loaded prices for {len(prices)} carriers, periods {periods} from {filepath.name}"
    )
    return prices


# ── Demand data (Munich_DH_data.xlsx) ─────────────────────────────────────────

def load_munich_demand(
    filepath: str | Path,
    sheet_name: str | int = "List1",
) -> pd.DataFrame:
    """
    Load hourly profiles from Munich_DH_data.xlsx.

    Generated by create_munich_data.py from DhnData.csv (Kaufmann et al., ECM 2026).
    All columns are re-sorted to calendar year (Jan–Dec).

    Returns a DataFrame with DatetimeIndex and columns:
        heat_demand              (MW, 2025 base)
        corrected_demand_YYYY    (MW, per investment period)
        electricity_price_YYYY   (€/MWh, flat per period, declining)
        sell_electricity_price_YYYY (€/MWh)
        supply_temp              (°C, measured T_VL_FW_C from DhnData.csv)
        return_temp              (°C, measured T_RL_FW_C from DhnData.csv)
        supply_temp_fixed        (°C, design value 90°C constant)
        return_temp_fixed        (°C, design value 55°C constant)
        ambient_temp             (°C, ERA5 southern Munich, same Apr22–Mar23 year)
    """
    filepath = Path(filepath)
    if not filepath.exists():
        raise DataLoadError(f"File not found: {filepath}")

    df = pd.read_excel(filepath, sheet_name=sheet_name)

    dt_strings = df["day"].astype(str) + " " + df["hour"].astype(str)
    df.index = pd.to_datetime(dt_strings, format="%d.%m.%Y %H:%M:%S")
    df.index.name = "datetime"

    result = pd.DataFrame(index=df.index)
    if "corrected_demand_2025" in df.columns:
        result["heat_demand"] = df["corrected_demand_2025"].values
    else:
        result["heat_demand"] = df.filter(like="corrected_demand").iloc[:, 0].values

    for yr in [2025, 2030, 2035, 2040, 2045]:
        col = f"corrected_demand_{yr}"
        if col in df.columns:
            result[col] = df[col].values

    # Supply and return temperatures (from DhnData.csv via create_munich_data.py)
    for col in ["supply_temp", "return_temp", "supply_temp_fixed", "return_temp_fixed",
                "ambient_temp"]:
        if col in df.columns:
            result[col] = df[col].values

    # Electricity buy/sell prices per period
    elec_found, sell_found = [], []
    for col in df.columns:
        col_str = str(col).strip()
        m_sell = re.match(r'sell[_\s]*electricity[_\s]*price[_\s]*(\d{4})$', col_str, re.I)
        m_buy  = re.match(r'electricity[_\s]*price[_\s]*(\d{4})$',          col_str, re.I)
        if m_sell:
            yr = int(m_sell.group(1))
            result[f"sell_electricity_price_{yr}"] = df[col].values
            sell_found.append(yr)
        elif m_buy:
            yr = int(m_buy.group(1))
            result[f"electricity_price_{yr}"] = df[col].values
            elec_found.append(yr)

    if len(result) != 8760:
        result = result.iloc[:8760].copy()
        logger.warning("Trimmed Munich demand profile to 8760 hours")

    logger.info(
        f"Loaded Munich demand: {len(result)} hours, "
        f"peak={result['heat_demand'].max():.2f} MW, "
        f"mean={result['heat_demand'].mean():.2f} MW"
    )
    if "supply_temp" in result.columns:
        logger.info(
            f"  Supply temp: {result['supply_temp'].min():.1f}–"
            f"{result['supply_temp'].max():.1f} °C  "
            f"| Return temp: {result['return_temp'].min():.1f}–"
            f"{result['return_temp'].max():.1f} °C"
        )
    return result


# ── Extra parameters (extra sheet) ────────────────────────────────────────────

def load_extra_parameters(filepath: str | Path) -> Dict[str, Any]:
    """
    Load discount rate and carbon price from 'extra' sheet.
    Carbon prices follow EUA escalation from 70 €/tCO₂ (2025) → 400 €/tCO₂ (2045).
    """
    filepath = Path(filepath)
    df = pd.read_excel(filepath, sheet_name="extra")

    year_cols: Dict[int, Any] = {}
    for col in df.columns:
        try:
            yr = int(str(col).strip())
            if 2000 <= yr <= 2100:
                year_cols[yr] = col
        except (ValueError, TypeError):
            pass

    if not year_cols:
        raise DataLoadError("No year columns found in 'extra' sheet.")

    # The year columns of this sheet ARE the investment milestone years.
    params: Dict[str, Any] = {"investment_years": sorted(year_cols.keys())}
    for _, row in df.iterrows():
        name = str(row["name"]).strip().lower()
        if name == "discount rate":
            params["discount_rate_by_period"] = {
                yr: float(row[col]) for yr, col in sorted(year_cols.items())
            }
        elif name == "carbon price":
            params["carbon_price_by_period"] = {
                yr: float(row[col]) for yr, col in sorted(year_cols.items())
            }
        elif name == "n_typical_days":
            # Scalar setting: take the first non-null value across the year columns.
            vals = [row[col] for col in year_cols.values() if pd.notna(row[col])]
            if not vals:
                raise DataLoadError("'n_typical_days' row has no value in the 'extra' sheet.")
            params["n_typical_days"] = int(round(float(vals[0])))
        elif name == "hthp_capex_scale":
            vals = [row[col] for col in year_cols.values() if pd.notna(row[col])]
            if vals:
                params["hthp_capex_scale"] = float(vals[0])

    for req in ("n_typical_days",):
        if req not in params:
            raise DataLoadError(
                f"'extra' sheet is missing the '{req}' row (expected name in column 'name')."
            )

    logger.info(
        f"Loaded extra parameters (periods {params['investment_years']}, "
        f"n_typical_days={params['n_typical_days']}) from {filepath.name}"
    )
    return params


# ── Geothermal brine resource ────────────────────────────────────────────────

def load_geothermal_resource(filepath: str | Path) -> Dict[str, float]:
    """
    Load the geothermal brine resource parameters from the 'Geothermal Resource'
    sheet (name / value / unit rows). These drive the SAPHEA capacity & COP
    calculation in run_rd.py — the geo direct-use, capacity-increase, HTHP
    evaporator and COP are all derived from these inputs instead of hard-coded.

    Returns a dict keyed by parameter name, e.g.::

        {"brine_mass_flow": 81.52, "brine_cp": 4.18, "T_prod": 106.0,
         "T_inject_min": 45.0, "T_return_design": 55.0, "direct_hx_pinch": 10.0,
         "carnot_eta": 0.4212, "p_brine_bar": 16.0}
    """
    filepath = Path(filepath)
    if "Geothermal Resource" not in pd.ExcelFile(filepath).sheet_names:
        raise DataLoadError(
            f"Sheet 'Geothermal Resource' not found in {filepath.name}. "
            "Add it with columns: parameter, value, unit."
        )
    df = pd.read_excel(filepath, sheet_name="Geothermal Resource")
    params = {
        str(row["parameter"]).strip(): float(row["value"])
        for _, row in df.iterrows()
        if pd.notna(row.get("parameter")) and pd.notna(row.get("value"))
    }
    required = {
        "brine_mass_flow", "brine_cp", "T_prod", "T_inject_min",
        "T_return_design", "direct_hx_pinch", "carnot_eta", "T_supply_design",
        "p_brine_bar",
    }
    missing = required - set(params)
    if missing:
        raise DataLoadError(
            f"'Geothermal Resource' sheet is missing parameters: {sorted(missing)}"
        )
    logger.info(
        f"Loaded geothermal resource ({params['brine_mass_flow']} kg/s, "
        f"{params['T_prod']}°C → {params['T_inject_min']}°C) from {filepath.name}"
    )
    return params


# ── HTHP CAPEX curve ──────────────────────────────────────────────────────────

def load_hthp_capex_curve(filepath: str | Path) -> list:
    """
    Load the HTHP specific-cost curve from the 'HTHP CAPEX Curve' sheet (the SAPHEA
    LSGEOHP cost regression: HP size → €/MW, with economies of scale). The model
    interpolates this curve at the derived HTHP size to pick its CAPEX.

    Returns a list of (size_MW, specific_cost_EUR_per_MW) tuples sorted by size.
    Returns [] if the sheet is absent (caller falls back to the tech-sheet CAPEX).
    """
    filepath = Path(filepath)
    if "HTHP CAPEX Curve" not in pd.ExcelFile(filepath).sheet_names:
        return []
    df = pd.read_excel(filepath, sheet_name="HTHP CAPEX Curve")
    pts = [
        (float(row["size_MW"]), float(row["specific_cost_EUR_per_MW"]))
        for _, row in df.iterrows()
        if pd.notna(row.get("size_MW")) and pd.notna(row.get("specific_cost_EUR_per_MW"))
    ]
    pts.sort(key=lambda p: p[0])
    if pts:
        logger.info(
            f"Loaded HTHP CAPEX curve ({len(pts)} points, "
            f"{pts[0][1]:,.0f}→{pts[-1][1]:,.0f} €/MW) from {filepath.name}"
        )
    return pts


# ── HP COP parameters ──────────────────────────────────────────────────────────

def load_hp_cop_parameters(filepath: str | Path) -> Dict[str, Dict[str, Any]]:
    """
    Load HP COP sensitivity parameters from 'HP COP' sheet.
    HTHP COP is not modelled via this sheet — it uses the SAPHEA Carnot formula
    with dynamic supply temperature, computed in run_rd.py after TSA.
    Sheet is empty; returns {}.
    """
    filepath = Path(filepath)
    df = pd.read_excel(filepath, sheet_name="HP COP")
    if df.empty:
        logger.info("HP COP sheet is empty — all HPs use fixed efficiency from tech sheet")
        return {}

    params: Dict[str, Dict[str, Any]] = {}
    for _, row in df.iterrows():
        t_type = str(row["type"]).strip()
        params[t_type] = {
            "sens_source":      float(row["COP source temperature sensitivity (1/°C)"]),
            "sens_flow":        float(row["COP flow temperature sensitivity (1/°C)"]),
            "sens_return":      float(row["COP return temperature sensitivity (1/°C)"]),
            "min_source_temp":  float(row["min shutoff source temperature (°C)"]),
            "fade_out_temp":    float(row["fade out temp where power reduction starts (°C)"]),
            "power_min_factor": 0.0,
            "nom_source_temp":  float(row.get("Source Temperature (°C)", 0.0)),
            "nom_flow_temp":    float(row["Nominal Inlet Temperature (°C)"]),
            "nom_return_temp":  float(row["Nominal Return Temperature (°C)"]),
        }
    return params


# ── Unit-commitment parameters ────────────────────────────────────────────────

def build_uc_params(technologies: Dict[str, Dict[str, Any]]) -> Dict | None:
    """
    Extract UC parameters from technology dict.
    Returns None when all start-up / ramp costs are zero (keeps model as LP).
    Munich's technologies have no start-up or ramp costs, so this returns None.
    """
    params = {
        name: {
            "c_startup":        data.get("coldstart_cost_EUR",   0.0),
            "c_ramp":           data.get("ramp_cost_EUR_per_MW", 0.0),
            "min_load_factor":  data.get("min_load_factor",      0.0),
            "cold_start_hours": data.get("cold_start_time_h",    0),
            "min_down_hours":   data.get("min_down_h",           0),
        }
        for name, data in technologies.items()
    }
    if all(
        v["c_startup"] == 0 and v["c_ramp"] == 0
        and v["min_load_factor"] == 0 and v["cold_start_hours"] == 0
        and v["min_down_hours"] == 0
        for v in params.values()
    ):
        return None
    return params


# ── Master loader ─────────────────────────────────────────────────────────────

def load_all_munich_data(
    tech_file:   str | Path,
    demand_file: str | Path,
) -> Tuple[Dict, Dict, Dict, pd.DataFrame, Dict, Dict]:
    """
    Load all Munich input data in one call.

    Parameters
    ----------
    tech_file   : path to Munich_tech_data.xlsx
    demand_file : path to Munich_DH_data.xlsx (generated by create_munich_data.py)

    Returns
    -------
    technologies : dict  — heat generator parameters
    storage      : dict  — storage parameters
    prices       : dict  — energy carrier prices / emission factors
    demand       : DataFrame — 8760-hour demand, electricity prices, temperature
    extra_params : dict  — discount rate, carbon price by period
    hp_params    : dict  — HP COP sensitivity (empty for Munich)
    """
    technologies = load_munich_technologies(tech_file)
    storage      = load_munich_storage(tech_file)
    prices       = load_energy_prices(tech_file)
    demand       = load_munich_demand(demand_file)
    extra_params = load_extra_parameters(tech_file)
    extra_params["geo_resource"]    = load_geothermal_resource(tech_file)
    extra_params["hthp_capex_curve"] = load_hthp_capex_curve(tech_file)
    hp_params    = load_hp_cop_parameters(tech_file)
    return technologies, storage, prices, demand, extra_params, hp_params


